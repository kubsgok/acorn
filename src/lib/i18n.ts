const TRANSLATIONS: Record<Lang, Dict> = { en, ms, ta, zh }

export function translate(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  let s = TRANSLATIONS[lang]?.[key] ?? TRANSLATIONS.en[key] ?? key
  if (vars) {
    for (const k of Object.keys(vars)) {
      s = s.split(`{${k}}`).join(String(vars[k]))
    }
  }
  return s
}

interface LangStore {
  lang: Lang
  setLang: (l: Lang) => void
  loadLang: () => Promise<void>
}

export const useLangStore = create<LangStore>((set) => ({
  lang: 'en',
  setLang: (lang) => {
    set({ lang })
    AsyncStorage.setItem(STORAGE_KEY, lang)
  },
  loadLang: async () => {
    const v = (await AsyncStorage.getItem(STORAGE_KEY)) as Lang | null
    if (v && TRANSLATIONS[v]) set({ lang: v })
  },
}))

// Hook: returns a `t` bound to the active language plus the current lang and a
// setter. Components using it re-render automatically when the language changes.
export function useT() {
  const lang = useLangStore((s) => s.lang)
  const setLang = useLangStore((s) => s.setLang)
  const t = (key: string, vars?: Record<string, string | number>) => translate(lang, key, vars)
  return { t, lang, setLang }
}
